#!/usr/bin/env python3
"""
Compile the mesh SDF compute kernels (Engine/GeometricRaster/Shaders/MeshSdf.slang) to SPIR-V through the Slang C API and write
them as a generated include that the Vulkan host embeds.

    python3 Tools/Build/BuildMeshSdfSpirv.py [--slang-lib PATH] [--out PATH]

Reuses the Slang binding and library lookup of BuildSolidArcSpirv.py. Slang validates the SPIR-V inside spCompile, so exit 0 means
both entries validated. Execution on a device is NOT part of this gate.
"""
import argparse
import ctypes
import importlib.util
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SHADER = REPO / "Engine/GeometricRaster/Shaders/MeshSdf.slang"
DEFAULT_OUT = REPO / "Engine/GeometricRaster/Generated/MeshSdfSpirv.inc"
ENTRIES = [("BakeMain", 6), ("CompositeMain", 6)]        # SLANG_STAGE_COMPUTE = 6
SPIRV_TARGET = 6
SOURCE_LANGUAGE_SLANG = 1
MATRIX_COLUMN_MAJOR = 2


def load_solidarc_helpers():
    spec = importlib.util.spec_from_file_location("solidarc_spirv", REPO / "Tools/Build/BuildSolidArcSpirv.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def compile_all(lib, helpers) -> dict:
    session = lib.spCreateSession(None)
    if not session:
        sys.exit("[MeshSdfSpirv] RED — spCreateSession failed")
    request = lib.spCreateCompileRequest(session)
    try:
        lib.spSetMatrixLayoutMode(request, MATRIX_COLUMN_MAJOR)
        lib.spAddSearchPath(request, str(SHADER.parent).encode())
        target = lib.spAddCodeGenTarget(request, SPIRV_TARGET)
        profile = lib.spFindProfile(session, b"spirv_1_5")
        lib.spSetTargetProfile(request, target, profile)
        unit = lib.spAddTranslationUnit(request, SOURCE_LANGUAGE_SLANG, b"MeshSdf")
        lib.spAddTranslationUnitSourceFile(request, unit, str(SHADER).encode())
        indices = {name: lib.spAddEntryPoint(request, unit, name.encode(), stage) for name, stage in ENTRIES}
        result = lib.spCompile(request)
        diagnostics = lib.spGetDiagnosticOutput(request)
        if diagnostics:
            print(diagnostics.decode(errors="replace"), file=sys.stderr)
        if result < 0:
            sys.exit(f"[MeshSdfSpirv] RED — spCompile returned {result:#x}")
        blobs = {}
        for name, _ in ENTRIES:
            size = ctypes.c_size_t(0)
            ptr = lib.spGetEntryPointCode(request, indices[name], ctypes.byref(size))
            if not ptr or size.value == 0:
                sys.exit(f"[MeshSdfSpirv] RED — no SPIR-V for {name}")
            blobs[name] = ctypes.string_at(ptr, size.value)
        return blobs
    finally:
        lib.spDestroyCompileRequest(request)
        lib.spDestroySession(session)


def write_include(blobs: dict, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["// Generated by Tools/Build/BuildMeshSdfSpirv.py from Engine/GeometricRaster/Shaders/MeshSdf.slang. Do not edit.", "#pragma once", "#include <cstdint>", "namespace MeshSdfSpirv {"]
    for name, blob in blobs.items():
        words = [int.from_bytes(blob[i:i + 4], "little") for i in range(0, len(blob), 4)]
        lines.append(f"inline constexpr uint32_t {name}[{len(words)}] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
        lines.append("};")
    lines.append("} // namespace MeshSdfSpirv")
    out.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--slang-lib", default=None)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    helpers = load_solidarc_helpers()
    lib = ctypes.CDLL(str(helpers.find_slang_library(args.slang_lib)))
    helpers.bind(lib)
    blobs = compile_all(lib, helpers)
    for name, blob in blobs.items():
        magic = int.from_bytes(blob[0:4], "little")
        if magic != 0x07230203:
            sys.exit(f"[MeshSdfSpirv] RED — {name} is not SPIR-V (magic {magic:#x})")
        print(f"[MeshSdfSpirv] {name:14s} {len(blob):6d} bytes SPIR-V")
    write_include(blobs, Path(args.out))
    print(f"[MeshSdfSpirv] GREEN — wrote {args.out}")


if __name__ == "__main__":
    main()
