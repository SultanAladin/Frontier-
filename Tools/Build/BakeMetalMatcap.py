#!/usr/bin/env python3
"""Bake the shared shiny chrome viewport matcap and its embedded C++ lookup table.

The source is the same analytic studio used for the SolidArc material previews. The resulting
128x128 PPM is sRGB for inspection/distribution; the C++ header packs those exact texels into
uint32 RGBA words for the SolidArc software raster and Frontier's Vulkan compute renderer.
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WIDTH = HEIGHT = 128
OUTPUT_PPM = ROOT / "EngineContent/Matcaps/MetalChrome.ppm"
OUTPUT_HEADER = ROOT / "Engine/DisplayPresentation/BakedMetalMatcap.h"


def clamp(value: float, lo: float, hi: float) -> float:
    return min(max(value, lo), hi)


def dot(a: tuple[float, float, float], b: tuple[float, float, float]) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def normalize(v: tuple[float, float, float]) -> tuple[float, float, float]:
    length = math.sqrt(dot(v, v))
    return tuple(component / length for component in v) if length > 1e-20 else v


def smoothstep(edge0: float, edge1: float, value: float) -> float:
    t = clamp((value - edge0) / (edge1 - edge0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def reflect(incident: tuple[float, float, float], normal: tuple[float, float, float]) -> tuple[float, float, float]:
    scale = 2.0 * dot(normal, incident)
    return tuple(incident[i] - scale * normal[i] for i in range(3))


def matcap_chrome(normal: tuple[float, float, float]) -> tuple[float, float, float]:
    # MatcapStudioSample(layer=1): neutral chrome, Metal=1, Roughness=0.05.
    key = normalize((-0.45, 0.65, 0.61))
    fill = normalize((0.7, -0.2, 0.68))
    view = (0.0, 0.0, 1.0)
    ndotv = clamp(normal[2], 0.0, 1.0)
    fresnel = (1.0 - ndotv) ** 4.0
    reflection = reflect(tuple(-v for v in view), normal)

    sky = smoothstep(-0.6, 1.0, reflection[1]) * 0.75 + 0.25
    floor = (1.0 - smoothstep(-0.9, 0.1, reflection[1])) * 0.5
    horizon = math.exp(-reflection[1] * reflection[1] * 10.0) * 0.5
    key_dot = clamp(dot(reflection, key), 0.0, 1.0)
    softbox = key_dot ** 4.0
    spark = key_dot ** 160.0
    fill_band = clamp(dot(reflection, fill), 0.0, 1.0) ** 2.5 * 0.30
    side = clamp(dot(reflection, normalize((0.9, 0.1, 0.3))), 0.0, 1.0) ** 3.0 * 0.18

    albedo = (0.92, 0.94, 0.97)
    roughness = 0.05
    blur = roughness * roughness
    sky_edge = 0.35 + 0.65 * smoothstep(-0.25, 0.35, reflection[1])
    contrast = sky_edge + (sky - sky_edge) * blur
    env_scalar = (0.18 + 0.62 * contrast - 0.12 * (floor + (0.25 - floor) * blur)
                  + 0.30 * (horizon + (0.15 - horizon) * blur)
                  + 0.75 * (softbox + (0.25 - softbox) * blur) + fill_band + side)
    environment = tuple(env_scalar * c for c in albedo)

    # The baked studio is metallic. Keep the direct reflection and tight pin highlight from the source shader.
    colour = tuple(albedo[i] * environment[i] * 1.25
                   + spark * (1.0 - roughness) * 1.1 * albedo[i]
                   + fresnel * 0.20 * albedo[i]
                   for i in range(3))
    return colour


def main() -> None:
    texels: list[tuple[int, int, int]] = []
    ppm = bytearray()
    for y in range(HEIGHT):
        for x in range(WIDTH):
            u = (x + 0.5) / WIDTH * 2.0 - 1.0
            v = 1.0 - (y + 0.5) / HEIGHT * 2.0
            r2 = u * u + v * v
            if r2 >= 1.0:
                normal = normalize((u, v, 0.02))
            else:
                normal = (u, v, math.sqrt(1.0 - r2))
            linear = matcap_chrome(normal)
            srgb = tuple(clamp(max(c, 0.0), 0.0, 1.0) ** (1.0 / 2.2) for c in linear)
            rgb = tuple(int(c * 255.0 + 0.5) for c in srgb)
            texels.append(rgb)
            ppm.extend(rgb)

    OUTPUT_PPM.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PPM.write_bytes(f"P6\n{WIDTH} {HEIGHT}\n255\n".encode("ascii") + ppm)

    words = [r | (g << 8) | (b << 16) | (0xFF << 24) for r, g, b in texels]
    lines = [
        "// Generated by Tools/Build/BakeMetalMatcap.py. Do not hand-edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace Frontier {",
        f"inline constexpr uint32_t kBakedMetalMatcapSize = {WIDTH}u;",
        f"inline constexpr uint32_t kBakedMetalMatcapWidth = {WIDTH}u;",
        f"inline constexpr uint32_t kBakedMetalMatcapHeight = {HEIGHT}u;",
        f"inline constexpr uint32_t kBakedMetalMatcapTexelCount = {WIDTH * HEIGHT}u;",
        "// Packed as R in bits 0..7, G in 8..15, B in 16..23, A in 24..31; bytes are sRGB.",
        f"inline constexpr uint32_t kBakedMetalMatcapPixels[{WIDTH * HEIGHT}] = {{",
    ]
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{word:08X}u" for word in words[i:i + 8]) + ",")
    lines.extend(["};", "} // namespace Frontier", ""])
    OUTPUT_HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Baked {WIDTH}x{HEIGHT} shiny chrome matcap: {OUTPUT_PPM.relative_to(ROOT)}")
    print(f"Embedded lookup table: {OUTPUT_HEADER.relative_to(ROOT)} ({OUTPUT_HEADER.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
