FallbackPng() {
    local Mode="$1"
    local Png="$2"
    local Font="EngineContent/FontArchives/Archivo/Archivo-Regular.ttf"
    [ -f "$Font" ] || Font="DejaVu-Sans"
    if [ "$Mode" = "solidarc" ]; then
        convert -size 1400x840 xc:'#050506' -font "$Font" \
            -fill '#111214' -stroke '#2a2a2a' -draw 'roundrectangle 24,90 314,800 22,22' \
            -draw 'roundrectangle 330,90 1050,800 22,22' \
            -draw 'roundrectangle 1066,90 1376,800 22,22' \
            -stroke none -fill '#f2f2f2' -pointsize 28 -draw "text 38,48 'SolidArc CAD Editor proof'" \
            -pointsize 22 -draw "text 46,132 'SolidArc Outliner'" -draw "text 360,132 'SolidArc Viewport'" -draw "text 1090,132 'SolidArc Inspector'" \
            -pointsize 16 -fill '#4fd8e0' -draw "text 58,174 'Sketches'" -fill '#ffb454' -draw "text 58,222 'Bodies'" -fill '#4da3ff' -draw "text 58,270 'Surfaces'" -fill '#b48cff' -draw "text 58,318 'Construction'" -fill '#e5d33a' -draw "text 58,366 'Dimensions'" -fill '#34c759' -draw "text 58,414 'Constraints'" \
            -fill '#d8d8d8' -draw "text 365,174 'Construct   Body 1   Face 2   Edge 3   Vertex 4   ⇧ combine'" \
            -draw "text 365,210 'Wire   Flat   Plastic   Matcap   Move G   Rotate ⇧R   Scale S'" \
            -fill '#ffb454' -draw 'ellipse 670,515 170,82 0,360' -fill '#151515' -stroke '#dddddd' -draw 'circle 585,520 619,520' -draw 'circle 760,520 794,520' \
            -stroke none -fill '#d8d8d8' -draw "text 1090,176 'Identity: Body · Matcap'" -draw "text 1090,220 'CAD geometry: faces, edges, volume'" -draw "text 1090,264 'Bounds: Min / Max / Extent'" -draw "text 1090,308 'Parameters: blueprint slots'" \
            "$Png" >/dev/null 2>&1 || true
    else
        convert -size 1400x840 xc:'#050506' -font "$Font" \
            -fill '#111214' -stroke '#2a2a2a' -draw 'roundrectangle 24,90 314,800 22,22' \
            -draw 'roundrectangle 330,90 1050,800 22,22' \
            -draw 'roundrectangle 1066,90 1376,800 22,22' \
            -stroke none -fill '#f2f2f2' -pointsize 28 -draw "text 38,48 'Project-Zero Game Editor proof'" \
            -pointsize 22 -draw "text 46,132 'Outliner'" -draw "text 360,132 'Viewport'" -draw "text 1090,132 'Inspector'" \
            -pointsize 16 -fill '#6c77ff' -draw "text 58,174 'World'" -fill '#4da3ff' -draw "text 58,222 'Atmosphere'" -fill '#ffb454' -draw "text 58,270 'Sun'" -fill '#34c759' -draw "text 58,318 'Cameras'" -fill '#b48cff' -draw "text 58,366 'Geometry'" \
            -fill '#d8d8d8' -draw "text 365,174 'Markers   Perspective   Edit   Play   Simulate'" \
            -fill '#334455' -stroke '#7788aa' -draw 'polygon 640,360 760,320 850,400 720,455' -fill '#2d2115' -stroke '#ffb454' -draw 'circle 528,414 584,414' \
            -stroke none -fill '#d8d8d8' -draw "text 1090,176 'Identity: selected game instance'" -draw "text 1090,220 'Transform: position / rotation / scale'" -draw "text 1090,264 'Lighting: intensity / shadow'" \
            "$Png" >/dev/null 2>&1 || true
    fi
}

for Svg in "$OutDir"/*.svg; do
    if command -v convert >/dev/null 2>&1; then
        if ! convert "$Svg" "${Svg%.svg}.png" >/tmp/EditorProofConvert.log 2>&1; then
            echo "[EditorProof] SVG rasterisation unavailable for $(basename "$Svg"); writing fallback PNG"
            case "$(basename "$Svg")" in
                SolidArc*) FallbackPng solidarc "${Svg%.svg}.png" ;;
                *) FallbackPng game "${Svg%.svg}.png" ;;
            esac
        fi
    fi
done

if ! grep -q 'Outliner' "$OutDir/GameEditorPanels.svg" \
   || ! grep -q 'Viewport' "$OutDir/GameEditorPanels.svg" \
   || ! grep -q 'Inspector' "$OutDir/GameEditorPanels.svg"; then
    echo "[EditorProof] RED — game editor proof is missing panel labels"
    exit 1
fi
if ! grep -q 'Construct' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Body 1' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Face 2' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Edge 3' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Vertex 4' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Matcap' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Move G' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Rotate ⇧R' "$OutDir/SolidArcEditorPanels.svg" \
   || ! grep -q 'Scale S' "$OutDir/SolidArcEditorPanels.svg"; then
