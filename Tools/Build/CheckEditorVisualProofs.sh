def txt(x,y,s,cls='small'):
    return f'<text x="{x}" y="{y}" class="{cls}">{s}</text>'

def chip(x,y,w,s,on=False):
    return f'<rect x="{x}" y="{y}" width="{w}" height="26" rx="13" class="{"chipOn" if on else "chip"}"/>{txt(x+12,y+17,s,"small")}'

