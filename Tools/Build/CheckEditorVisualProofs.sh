from pathlib import Path
out = Path('Exhibits/Gallery/EditorPanels')
out.mkdir(parents=True, exist_ok=True)

CSS = '''<style>
.bg{fill:#050506}.panel{fill:#111214;stroke:#2a2a2a;stroke-width:1}.panel2{fill:#0b0c0e;stroke:#2a2a2a;stroke-width:1}.title{font:300 22px Arial,sans-serif;fill:#f2f2f2}.label{font:600 13px Arial,sans-serif;fill:#d8d8d8}.small{font:12px monospace;fill:#9a9a9a}.chip{fill:#202124;stroke:#414246;stroke-width:1}.chipOn{fill:#34363a;stroke:#666;stroke-width:1}.cad{fill:#4fd8e0}.orange{fill:#ffb454}.yellow{fill:#e5d33a}.blue{fill:#4da3ff}.violet{fill:#b48cff}.green{fill:#34c759}.dim{fill:#898989}.game{fill:#6c77ff}.row{fill:#18191b;stroke:#28292c;stroke-width:1}.proof{font:11px monospace;fill:#777}
